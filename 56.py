# 将字符串按行分割并转为DataFrame
from io import StringIO
df = pd.read_csv(StringIO(data), header=None, names=['X', 'Y'])

# 3. 提取自变量X和因变量Y（sklearn要求X为二维数组）
X = df[['X']].values  # 自变量（二维数组）
Y = df['Y'].values    # 因变量（一维数组）

# 4. 拟合线性回归模型
model = LinearRegression()
model.fit(X, Y)

# 5. 提取模型参数并输出结果
beta0 = model.intercept_    # 截距β₀
beta1 = model.coef_[0]      # 斜率β₁
y_pred = model.predict(X)   # 预测值
r2 = r2_score(Y, y_pred)    # 决定系数R²

# 打印核心结果
print("="*50)
print("线性回归模型结果")
print("="*50)
print(f"回归方程：Ŷ = {beta0:.4f} + {beta1:.4f}X")
print(f"截距 β₀：{beta0:.4f}")
print(f"斜率 β₁：{beta1:.4f}")
print(f"决定系数 R²：{r2:.4f}")
print("="*50)

# 6. 输出前5组数据的实际值与预测值对比
print("\n前5组数据实际值 vs 预测值")
print("-"*35)
comparison = pd.DataFrame({
    'X': X[:5].flatten(),
    '实际Y': Y[:5],
    '预测Ŷ': y_pred[:5]
})
print(comparison.round(4))

# 7. 可视化：散点图（原始数据）+ 回归线（预测模型）
