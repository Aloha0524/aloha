# 绘制回归线（用X的最小值和最大值生成连续线段）
x_line = np.linspace(X.min(), X.max(), 100).reshape(-1, 1)
y_line = model.predict(x_line)
plt.plot(x_line, y_line, color='darkblue', linewidth=2, label=f'回归线：Ŷ={beta0:.2f}+{beta1:.2f}X')

# 图表标签与图例
plt.xlabel('自变量 X', fontsize=12)
